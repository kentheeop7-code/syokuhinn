// 状況から、おすすめを選ぶ（トレーナーの手助け。最後は、トレーナーが決める）
export function suggestTip(o: { constipation?: boolean; sleepLow?: boolean; muscleLoss?: boolean; train?: boolean }): string {
  if (o.sleepLow) return "melatonin";
  if (o.constipation) return "fiber";
  if (o.muscleLoss || o.train) return "protein";
  return "inulin";
}
