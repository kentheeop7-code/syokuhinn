export const getTip = (id: string) => TIPS.find((t) => t.id === id);

// 状況から、おすすめを選ぶ（トレーナーの手助け。最後は、トレーナーが決める）
export function suggestTip(o: { constipation?: boolean; sleepLow?: boolean; muscleLoss?: boolean; train?: boolean }): string {
  if (o.sleepLow) return "melatonin";
  if (o.constipation) return "fiber";
  if (o.muscleLoss || o.train) return "protein";
  return "inulin";
}

export function tipText(id: string): string {
  const t = getTip(id);
  if (!t) return "";
  return [
    `■ 豆知識：${t.icon} ${t.name}`,
    t.hook,
    "",
    `とは：${t.what}`,
    "",
    "とれる食べ物・工夫：",
    ...t.foods.map((x) => `・${x}`),
    "",
    "とり方のコツ：",
    ...t.how.map((x) => `・${x}`),
    "",
    `⚠ ${t.caution.slice(0, 2).join(" ／ ")}`,
    "",
    "覚えておくこと：",
    ...t.remember.map((x, i) => `${i + 1}. ${x}`),
  ].join("\n");
}

// 定期フォローで送る豆知識を、状況から、自動で選ぶ（最大3つ）。毎回、ちがう内容になるよう、回数で、ずらす。
export function autoTips(o: { constipation?: boolean; sleepLow?: boolean; stall?: boolean; train?: boolean; round?: number; max?: number }): { ids: string[]; reasons: string[] } {
  const max = o.max ?? 3;
  const ids: string[] = [];
  const reasons: string[] = [];
  const add = (id: string, why: string) => {
    if (ids.length < max && !ids.includes(id)) {
      ids.push(id);
      reasons.push(`${getTip(id)!.name.replace(/（.*$/, "")}：${why}`);
    }
  };
  if (o.sleepLow) add("sleepdiet", "睡眠が短い");
  if (o.constipation) {
    add("fiberfoods", "便通が気になる");
    add("gutbiome", "便通が気になる");
  }
  if (o.stall) add("dietchoose", "体重が止まっている");
  if (o.train) add("protein", "筋トレをしている");
  const pool = ["fiberfoods", "gutbiome", "sleepdiet", "dietchoose", "inulin", "ferment", "magnesium", "protein", "kiwi", "natto", "fiber", "melatonin"];
  const start = Math.max(0, (o.round ?? 1) - 1) * max;
  for (let i = 0; i < pool.length && ids.length < max; i++) add(pool[(start + i) % pool.length], "今回の定期フォローの、おすすめ（回ごとに、入れかえ）");
  return { ids, reasons };
}
