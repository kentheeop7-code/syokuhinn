const num = (s: string) => parseFloat(s.replace(/[０-９．]/g, (c) => (c === "．" ? "." : String(c.charCodeAt(0) - 0xff10)))) || 0;
const has = (t: string, re: RegExp) => re.test(t);

// 文章から、期間（週）を読む：「2ヶ月」「8週間」「1週間」
function weeksIn(t: string): number {
  const m = t.match(/([0-9０-９]+(?:\.[0-9]+)?)\s*(?:か|ヶ|ケ|カ|ｶ)?\s*月/);
  if (m) return Math.round(num(m[1]) * 4.3);
  const w = t.match(/([0-9０-９]+)\s*週/);
  if (w) return num(w[1]);
  if (/半年/.test(t)) return 26;
  return 0;
}
// 筋肉が○kg落ちた
function muscleKg(t: string): number {
  const m = t.match(/筋肉[量]?[^。、\n]{0,10}?([0-9０-９]+(?:\.[0-9]+)?)\s*(?:kg|ｋｇ|キロ|㎏)/i) || t.match(/([0-9０-９]+(?:\.[0-9]+)?)\s*(?:kg|ｋｇ|キロ|㎏)[^。、\n]{0,8}?筋肉/i);
  return m ? num(m[1]) : 0;
}

