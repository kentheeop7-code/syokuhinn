export const getBreaker = (id: string) => BREAKERS.find((b) => b.id === id);

// 状況から、候補を、自動で選ぶ（トレーナーが、あとで、直せる）
export function suggestBreakers(c: { stall: boolean; weeksStalled: number; gut: boolean; youth: boolean; cond: boolean; noReduce: boolean }): string[] {
  const out: string[] = [];
  const add = (id: string) => !out.includes(id) && out.push(id);
  if (c.youth) return ["log", "life", "addfoods"];
  if (c.stall || c.noReduce) {
    add("log");
    add("measure");
  }
  if (c.weeksStalled >= 4) {
    add("dietbreak");
    if (!c.cond) add("refeed");
  }
  if (c.stall) add("life");
  if (c.gut) add("gut");
  if (!c.cond && (c.stall || c.noReduce)) add("fast16");
  add("addfoods");
  return out.slice(0, 5);
}
