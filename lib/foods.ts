export const portionsOf = (food: Food): Portion[] =>
  PORTIONS[food.name] ?? CAT_PORTIONS[food.cat];

// 「約1.5×茶碗1杯」のように、量を目安の大きさで表す
export function describeAmount(food: Food, grams: number): string {
  const ps = portionsOf(food);
  let best: { p: Portion; r: number } | null = null;
  for (const p of ps) {
    const r = grams / p.g;
    if (!best || Math.abs(Math.log(r)) < Math.abs(Math.log(best.r))) best = { p, r };
  }
  if (!best) return "";
  const r = Math.round(best.r * 10) / 10;
  if (r >= 0.9 && r <= 1.1) return best.p.label;
  if (r < 0.2) return "";
  return `${best.p.label}の約${r}倍`;
}
