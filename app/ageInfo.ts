// 年齢ごとの、ダイエットの考え方（食事摂取基準2025・骨粗鬆症/高齢者肥満症のガイドラインなどを参考にした一般的な目安）
export type AgeBand = "u40" | "m40" | "s60";

export const ageBand = (age: number): AgeBand => (age < 40 ? "u40" : age < 60 ? "m40" : "s60");

// 1か月に減らしてよい量の目安（体重に対する割合・%）
export const MONTHLY_CAP_PCT: Record<AgeBand, number> = { u40: 4, m40: 3, s60: 2 };

export const BAND_LABEL: Record<AgeBand, string> = {
  u40: "18〜39歳",
  m40: "40〜59歳",
  s60: "60歳以上",
};

export type AgeNote = { title: string; items: string[] };

// カルシウム推奨量（mg/日・30〜74歳）：男性750、女性650。ビタミンDの目安量：9.0μg/日
export function ageNotes(band: AgeBand, sex: "m" | "f" | null): AgeNote {
  const ca = sex === "f" ? "650mg" : sex === "m" ? "750mg" : "男性750mg・女性650mg";
  if (band === "u40") {
    return {
      title: "30代前後のダイエット：骨を守りながら、筋肉を減らさない",
      items: [
        "骨の量（最大骨量）は20歳前後でピークになり、40代ごろまでは保たれます。今の減量が骨にひびかないよう、食事を減らしすぎないことが大切です。",
        "女性は、食事を極端に減らして月経が止まる（無月経）と、女性ホルモンが下がって骨密度が低下します。月経が乱れたら、減量を止めて、食事量を戻してください。",
        "BMIが18.5未満の「やせ」は、骨密度が下がり、将来の骨折リスクが高まります。目標体重は、BMI18.5以上にしましょう。",
        `カルシウムは1日${ca}、ビタミンDは9.0μgが目安。乳製品・小魚・大豆製品と、魚・きのこを。`,
        "1か月の減量は、体重の約3〜4%まで。体力があるので、筋トレは強めでも、有酸素運動と組み合わせて進められます。",
      ],
    };
  }
  if (band === "m40") {
    return {
      title: "40〜50代のダイエット：筋肉と骨の減りが始まる時期",
      items: [
        "基礎代謝が下がり、同じ食事でも太りやすくなります。筋トレで筋肉を保つことが、いちばんの対策です。",
        "女性は、閉経の前後から女性ホルモンが減り、骨量が急に減りやすくなります。この時期の過度な食事制限は、骨にもひびきます。",
        `カルシウムは1日${ca}、ビタミンDは9.0μgを目安に、毎日とりましょう（骨を守る食事）。`,
        "たんぱく質は、体重1kgあたり1.5g前後までが目安。毎食20〜30gに分けてとります。",
        "運動は、筋トレ（週2〜3回）に加えて、骨に刺激を与える「荷重運動」（ウォーキング、階段、ジョギング）を組み合わせます。",
        "1か月の減量は、体重の約2〜3%まで。",
      ],
    };
  }
  return {
    title: "60歳以上のダイエット：急がず、筋肉と骨を守るのが第一",
    items: [
      "加齢で、筋肉（サルコペニア）と骨（骨粗しょう症）が減りやすくなっています。やせるだけの減量は、筋肉と骨を弱らせ、転倒・骨折やフレイルにつながるおそれがあります。",
      "減量は、ゆっくり。1か月に減らすのは、体重の約1〜2%までが目安です。食事を減らす幅も小さめ（このアプリでは、1割弱）にしています。",
      "たんぱく質は、体重1kgあたり1.0〜1.3gを、毎食に分けて。減量中でも、筋肉を守るために減らさないことが大切です。腎臓の病気がある人は、必ず医師に相談を。",
      "必ずレジスタンス運動（筋トレ）を組み合わせてください。ガイドラインでは、運動を併用した減量では、骨密度が減らないとされています。",
      `カルシウムは1日${ca}、ビタミンDは9.0μg。魚・きのこ・乳製品に加え、日光を浴びる習慣を。ビタミンKの多い納豆・緑黄色野菜も。`,
      "65歳以上の目標BMIは21.5〜24.9。BMIが低いほど良いわけではありません。やせすぎは低栄養・骨折のリスクです。",
      "ケトジェニックなど、極端な糖質制限は向きません。持病や服薬（糖尿病・腎臓・骨の薬など）がある人は、始める前に必ず医師に相談を。",
    ],
  };
}

