function total(m: Menu) {
  let kcal = 0,
    p = 0,
    fi = 0,
    salt = 0;
  for (const meal of m.meals)
    for (const i of meal.items) {
      const f = byName.get(i.name);
      if (!f) continue;
      const k = i.g / 100;
      kcal += (f.p * 4 + f.f * 9 + f.c * 4) * k;
      p += f.p * k;
      fi += f.fi * k;
      salt += f.salt * k;
    }
  return { kcal: Math.round(kcal), p: Math.round(p), fi: Math.round(fi * 10) / 10, salt: Math.round(salt * 10) / 10 };
}

